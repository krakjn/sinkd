#!/usr/bin/env bash
# Build an Arch package (sinkd-*.pkg.tar.zst) into pkg/artifacts/.
# The binary is static musl with libreflect.a linked in.
set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd -- "$SCRIPT_DIR/../.." && pwd)
cd "$ROOT"

if ! command -v bump >/dev/null 2>&1; then
  echo "bump not found. Install bump (https://github.com/launchfirestorm/bump) and ensure it is on PATH." >&2
  exit 1
fi

if ! command -v makepkg >/dev/null 2>&1; then
  echo "makepkg not found. Install base-devel (pacman -S base-devel) on Arch." >&2
  exit 1
fi

VERSION=$(bump -b)

case "$(uname -m)" in
  x86_64) MUSL_TARGET=x86_64-unknown-linux-musl ;;
  aarch64) MUSL_TARGET=aarch64-unknown-linux-musl ;;
  *) echo "unsupported machine $(uname -m)" >&2; exit 1 ;;
esac

OUT="${ROOT}/pkg/artifacts"
mkdir -p "${OUT}"

WORKDIR=$(mktemp -d)
cleanup() { rm -rf "${WORKDIR}"; }
trap cleanup EXIT

cat >"${WORKDIR}/PKGBUILD" <<EOF
# Generated by pkg/arch/create.sh — version from \`bump -b\` / bump.toml
pkgname=sinkd
pkgver=${VERSION}
pkgrel=1
pkgdesc="Hub-and-spoke file sync (Zenoh control, libreflect data)"
arch=('x86_64' 'aarch64')
url="https://gitlab.com/ballast-dev/sinkd"
license=('GPL-3.0-or-later')
depends=()
makedepends=()
options=('!lto' '!debug')

build() {
  cd "$ROOT"
  _bin="\${CARGO_TARGET_DIR:-$ROOT/target}/${MUSL_TARGET}/release/sinkd"
  _bin_srv="\${CARGO_TARGET_DIR:-$ROOT/target}/${MUSL_TARGET}/release/sinkd-srv"
  if [[ -s "\$_bin" && -s "\$_bin_srv" ]]; then
    return 0
  fi
  export PATH="\$HOME/.cargo/bin:\$PATH"
  cargo build -p sinkd -p sinkd-srv --release --locked --target ${MUSL_TARGET}
}

package() {
  _bin="\${CARGO_TARGET_DIR:-$ROOT/target}/${MUSL_TARGET}/release/sinkd"
  _bin_srv="\${CARGO_TARGET_DIR:-$ROOT/target}/${MUSL_TARGET}/release/sinkd-srv"
  install -Dm755 "\${_bin}" "\${pkgdir}/usr/bin/sinkd"
  install -Dm755 "\${_bin_srv}" "\${pkgdir}/usr/bin/sinkd-srv"
  install -Dm644 "$ROOT/sinkd-cfg/server.toml" "\${pkgdir}/etc/sinkd/server.toml"
  install -Dm644 "$ROOT/sinkd-cfg/client.toml" "\${pkgdir}/usr/share/sinkd/client.toml"
  install -Dm644 "$ROOT/pkg/systemd/sinkd-srv.service" "\${pkgdir}/usr/lib/systemd/system/sinkd-srv.service"
  install -Dm644 "$ROOT/pkg/systemd/sinkd.service" "\${pkgdir}/usr/lib/systemd/user/sinkd.service"
  if [[ -f "$ROOT/LICENSE" ]]; then
    install -Dm644 "$ROOT/LICENSE" "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"
  fi
}
EOF

(
  cd "${WORKDIR}"
  makepkg -fs --cleanbuild --noconfirm
)

shopt -s nullglob
for f in "${WORKDIR}"/*.pkg.tar.zst; do
  mv -f "${f}" "${OUT}/"
  echo "Wrote ${OUT}/$(basename "${f}")"
done
